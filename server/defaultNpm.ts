import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type {
  DefaultActionResponse,
  ScanResult,
} from '../shared/types';
import { HttpError } from './http';
import { getScan, invalidateScan } from './scanner';
import {
  ATLAS_PATHS,
  IS_WINDOWS,
  NPX_BIN,
  buildManualSnippet,
  buildShellSnippet,
  clearStoredState,
  detectShell,
  isAtlasWrapperPath,
  isExecutable,
  isIntegrationInstalled,
  removeShellIntegration,
  shellQuote,
  shortPath,
  syncShellIntegration,
  writeStoredState,
} from './settings';

function wrapperScript(binPath: string): string {
  return [
    '#!/bin/sh',
    `# Generated by npm-atlas at ${new Date().toISOString()}. Do not edit.`,
    `BIN=${shellQuote(binPath)}`,
    `PATH=${shellQuote(path.dirname(binPath))}:"$PATH"`,
    'export PATH',
    'exec "$BIN" "$@"',
    '',
  ].join('\n');
}

async function writeExecutable(file: string, content: string): Promise<void> {
  const temp = `${file}.tmp-${process.pid}-${Date.now()}`;
  await writeFile(temp, content, { mode: 0o755 });
  await rename(temp, file);
}

export async function setDefaultNpm(
  scanResult: ScanResult,
  installationId: string,
): Promise<DefaultActionResponse> {
  if (IS_WINDOWS) {
    throw new HttpError(400, 'Windows 暂不支持在应用内切换默认 npm');
  }

  const installation = scanResult.installations.find(
    (entry) => entry.id === installationId,
  );
  if (!installation) {
    throw new HttpError(400, '未找到该 npm 安装，请刷新后重试');
  }
  if (isAtlasWrapperPath(installation.path)) {
    throw new HttpError(400, 'npm-atlas 的包装器不能作为默认目标');
  }
  if (!(await isExecutable(installation.path))) {
    throw new HttpError(400, '该 npm 可执行文件不存在或不可执行');
  }

  await mkdir(ATLAS_PATHS.wrapperDir, { recursive: true });
  await writeExecutable(
    ATLAS_PATHS.wrapperNpm,
    wrapperScript(installation.path),
  );

  const npxPath = path.join(path.dirname(installation.path), NPX_BIN);
  if (await isExecutable(npxPath)) {
    await writeExecutable(ATLAS_PATHS.wrapperNpx, wrapperScript(npxPath));
  } else {
    await rm(ATLAS_PATHS.wrapperNpx, { force: true });
  }

  const updatedAt = new Date().toISOString();
  await writeStoredState({
    version: 1,
    targetPath: installation.path,
    targetRealPath: installation.realPath,
    npmVersion: installation.version,
    nodeVersion: installation.nodeVersion,
    source: installation.source,
    updatedAt,
  });

  const shell = detectShell();
  const snippet = buildShellSnippet(shell.shell);
  const messages: string[] = [];

  if (snippet && shell.supported) {
    try {
      const result = await syncShellIntegration(snippet);
      if (result?.changed) {
        messages.push(
          `已更新 ${shortPath(shell.rcFile)} 的 PATH 配置${
            result.backup ? `（原文件备份：${shortPath(result.backup)}）` : ''
          }。`,
        );
      } else {
        messages.push(`${shortPath(shell.rcFile)} 的 PATH 配置已是最新。`);
      }
    } catch (cause) {
      messages.push(
        `无法写入 ${shortPath(shell.rcFile)}：${
          cause instanceof Error ? cause.message : String(cause)
        }`,
      );
      messages.push(`请手动将 ${ATLAS_PATHS.wrapperDir} 放到 PATH 最前。`);
    }
  } else {
    messages.push(
      `无法自动识别 shell 配置，请手动将 ${ATLAS_PATHS.wrapperDir} 放到 PATH 最前。`,
    );
    messages.push(buildManualSnippet());
  }

  messages.push('新开终端（或 source 对应配置文件）后生效。');

  invalidateScan();
  const fresh = await getScan(true);

  return { scan: fresh, messages };
}

export async function resetDefaultNpm(): Promise<DefaultActionResponse> {
  await clearStoredState();
  await rm(ATLAS_PATHS.wrapperNpm, { force: true });
  await rm(ATLAS_PATHS.wrapperNpx, { force: true });
  await rm(ATLAS_PATHS.wrapperDir, { recursive: true, force: true });

  const shell = detectShell();
  const messages: string[] = [];
  let removedBlock = false;

  if (await isIntegrationInstalled(shell.rcFile)) {
    try {
      const result = await removeShellIntegration();
      if (result?.changed) {
        removedBlock = true;
        messages.push(
          `已从 ${shortPath(shell.rcFile)} 移除 npm-atlas 的 PATH 配置${
            result.backup ? `（备份：${shortPath(result.backup)}）` : ''
          }。`,
        );
      }
    } catch (cause) {
      messages.push(
        `移除 PATH 配置失败：${
          cause instanceof Error ? cause.message : String(cause)
        }`,
      );
    }
  }

  if (!removedBlock) {
    messages.push('npm-atlas 的默认 npm 设置已移除。');
  }
  messages.push('新开终端后恢复为系统 PATH 决定的默认 npm。');

  invalidateScan();
  const fresh = await getScan(true);
  return { scan: fresh, messages };
}